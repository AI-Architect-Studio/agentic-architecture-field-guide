// Optional browser checks; the workbench itself has no package dependencies.
import { createRequire } from 'node:module';
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const playwright = process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES
  ? require(resolve(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES, 'playwright')) : require('playwright');
const out = resolve(process.env.WORKBENCH_QA_DIR || 'workbench-qa');
await mkdir(out, { recursive: true });
const browser = await playwright.chromium.launch({ headless: true,
  ...(process.env.WORKBENCH_CHROMIUM_PATH ? { executablePath: process.env.WORKBENCH_CHROMIUM_PATH } : {}) });
const checks = [];
const check = (condition, label) => { assert.ok(condition, label); checks.push(label); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  const page = await context.newPage();
  const errors = [], remoteRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (/^https?:/u.test(request.url())) remoteRequests.push(request.url()); });
  page.on('dialog', dialog => dialog.accept());
  const url = new URL('./index.html', import.meta.url).href;
  await page.goto(url);
  check(await page.title() === 'Client Delivery Workbench · Starlight', 'Workbench opens offline');
  check(await page.locator('#count').innerText() === '0', 'Blank project reports zero filled fields');
  check(await page.evaluate(() => localStorage.getItem('starlight-client-delivery-v1')) === null, 'No automatic storage');
  await page.click('#sample');
  check(await page.inputValue('#project-name') === 'Northstar support assistant', 'Synthetic example loads');
  check((await page.locator('#sample-note').innerText()).includes('Synthetic example'), 'Example remains visibly synthetic');
  await page.waitForSelector('#message', { state: 'hidden' });
  await page.screenshot({ path: resolve(out, 'workbench-desktop.png'), fullPage: true, animations: 'disabled' });
  await page.fill('#project-name', 'Example <img src=x onerror="window.attacked=true">');
  check(await page.locator('#summary-name img').count() === 0, 'User text is rendered as text, not markup');
  check(await page.evaluate(() => window.attacked) === undefined, 'Injected image event does not execute');
  await page.click('#save-local');
  check((await page.locator('#save-state').innerText()).includes('saved manually'), 'Storage requires deliberate save');
  await page.reload();
  check(await page.inputValue('#project-name') === '', 'Reload does not silently restore private data');
  await page.click('#restore-local');
  check((await page.inputValue('#project-name')).includes('<img'), 'Explicit restore recovers exact text');
  await page.click('#tab-brief');
  await page.locator('#tab-brief').focus();
  await page.keyboard.press('ArrowRight');
  check(await page.locator('#tab-architecture').getAttribute('aria-selected') === 'true', 'Tabs support keyboard navigation');
  await page.click('#tab-evidence');
  await page.selectOption('#evidence-state-boundary', 'reviewed');
  check(await page.inputValue('#evidence-state-boundary') === 'missing', 'Review status requires reference and reviewer');
  await page.fill('#evidence-boundary-reference', 'redacted://case/1');
  await page.fill('#evidence-boundary-reviewer', 'Test reviewer');
  await page.selectOption('#evidence-state-boundary', 'reviewed');
  await page.fill('#evidence-boundary-reviewer', '');
  check(await page.inputValue('#evidence-state-boundary') === 'missing', 'Removing reviewer invalidates recorded review');
  await page.click('#tab-handover');
  check((await page.locator('#report').innerText()).includes('Release approved: No. Runtime verified by this tool: No.'), 'Handover preserves unverified and unapproved state');
  let downloadPromise = page.waitForEvent('download');
  await page.click('#export-json');
  let download = await downloadPromise;
  const jsonPath = resolve(out, 'roundtrip.json'); await download.saveAs(jsonPath);
  const exported = JSON.parse(await readFile(jsonPath, 'utf8'));
  check(exported.releaseApproved === false && exported.runtimeVerified === false, 'JSON export cannot promote release state');
  downloadPromise = page.waitForEvent('download'); await page.click('#export-md'); download = await downloadPromise;
  const mdPath = resolve(out, 'handover.md'); await download.saveAs(mdPath);
  check((await readFile(mdPath, 'utf8')).includes('\\<img'), 'Markdown escapes injected markup');
  await page.click('#new'); await page.setInputFiles('#import-file', jsonPath);
  await page.waitForFunction(value => document.getElementById('project-name').value === value, exported.project.name);
  check(await page.inputValue('#project-name') === exported.project.name, 'JSON export/import round-trip preserves project');
  const original = await page.inputValue('#project-name');
  const invalid = structuredClone(exported); invalid.releaseApproved = true;
  await page.setInputFiles('#import-file', { name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(invalid)) });
  await page.waitForFunction(() => document.getElementById('message').textContent.includes('not a supported'));
  check(await page.inputValue('#project-name') === original && (await page.locator('#message').innerText()).includes('not a supported'), 'Invalid import rejected without replacing project');
  await page.evaluate(() => localStorage.setItem('workbench-unrelated-test-sentinel', 'preserve'));
  await page.click('#forget-local');
  check(await page.evaluate(() => localStorage.getItem('starlight-client-delivery-v1') === null && localStorage.getItem('workbench-unrelated-test-sentinel') === 'preserve'), 'Remove saved copy affects only owned key');
  await page.click('#sample');
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile brief has no horizontal overflow');
  await page.waitForSelector('#message', { state: 'hidden' });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: resolve(out, 'workbench-mobile.png'), fullPage: true, animations: 'disabled' });
  await page.click('#tab-evidence');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile evidence has no horizontal overflow');
  await page.click('#tab-handover');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile handover has no horizontal overflow');
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.emulateMedia({ media: 'print' });
  check(await page.locator('#print-view').isVisible() && !(await page.locator('.shell').isVisible()), 'Print view contains the packet without editor controls');
  await page.pdf({ path: resolve(out, 'workbench-print.pdf'), format: 'A4' });
  check(errors.length === 0, 'No uncaught browser errors');
  check(remoteRequests.length === 0, 'No remote network requests');
  console.log(JSON.stringify({ passed: checks.length, checks, captures: out }, null, 2));
} finally { await browser.close(); }
